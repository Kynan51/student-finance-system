from django.conf import settings
from django.db import models


class FinancialInsight(models.Model):
    """
    A dated, explainable insight generated by the analytics engine.
    Each record stores the metrics and assumptions that support it so the
    student (and a project supervisor) can see *why* it was produced.
    """

    class Kind(models.TextChoices):
        RUNWAY = "runway", "Financial runway"
        FORECAST = "forecast", "Balance forecast"
        SHORTFALL = "shortfall", "Possible shortfall"
        TREND = "trend", "Spending trend"
        ANOMALY = "anomaly", "Unusual spending"
        BUDGET = "budget", "Budget alert"
        CATEGORY = "category", "Category pattern"
        DATA = "data", "Data quality"

    class Severity(models.TextChoices):
        INFO = "info", "Info"
        POSITIVE = "positive", "Positive"
        WARNING = "warning", "Warning"
        DANGER = "danger", "Danger"

    class Reliability(models.TextChoices):
        LOW = "low", "Low"
        MEDIUM = "medium", "Medium"
        HIGH = "high", "High"

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="insights"
    )
    kind = models.CharField(max_length=12, choices=Kind.choices)
    severity = models.CharField(max_length=10, choices=Severity.choices, default=Severity.INFO)
    title = models.CharField(max_length=120)
    message = models.TextField()
    metrics = models.JSONField(default=dict, blank=True)
    assumptions = models.TextField(blank=True)
    reliability = models.CharField(max_length=6, choices=Reliability.choices, default=Reliability.LOW)
    data_fingerprint = models.CharField(max_length=64, db_index=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at", "kind"]
        indexes = [models.Index(fields=["owner", "-created_at"], name="insight_owner_created_idx")]

    def __str__(self):
        return f"{self.get_kind_display()}: {self.title}"


class Notification(models.Model):
    class Level(models.TextChoices):
        INFO = "info", "Info"
        SUCCESS = "success", "Success"
        WARNING = "warning", "Warning"
        DANGER = "danger", "Danger"

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="notifications"
    )
    level = models.CharField(max_length=10, choices=Level.choices, default=Level.INFO)
    title = models.CharField(max_length=120)
    message = models.CharField(max_length=300)
    link = models.CharField(max_length=200, blank=True)
    dedupe_key = models.CharField(max_length=120, blank=True, db_index=True)
    is_read = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["is_read", "-created_at"]
        indexes = [models.Index(fields=["owner", "is_read"], name="notif_owner_read_idx")]

    def __str__(self):
        return self.title
